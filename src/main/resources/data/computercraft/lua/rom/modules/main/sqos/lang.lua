local tables = { de = de, en = en }

function M.set(code)
    if tables[code] then M.code = code end
end

function M.languages()
    return { "de", "en" }
end

function M.t(key, ...)
    local s = M.con and (tables[M.code]["con_" .. key] or de["con_" .. key]) or tables[M.code][key] or de[key] or key
    if select("#", ...) > 0 then
        local ok, r = pcall(string.format, s, ...)
        if ok then return r end
    end
    return s
end

return M
