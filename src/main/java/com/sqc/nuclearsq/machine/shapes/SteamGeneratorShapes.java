    @SafeVarargs
    private static <T> T[] join(T[]... parts) {
        int n = 0;
        for (T[] p : parts) n += p.length;
        T[] out = java.util.Arrays.copyOf(parts[0], n);
        int i = parts[0].length;
        for (int k = 1; k < parts.length; k++) {
            System.arraycopy(parts[k], 0, out, i, parts[k].length);
            i += parts[k].length;
        }
        return out;
    }
